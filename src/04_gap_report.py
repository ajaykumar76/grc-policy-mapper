"""
Build a gap report: which controls in the illustrative 'must cover' set have
policy support (from the LLM-verified mapping) and which do not.

Usage:  python src\\04_gap_report.py     (run 03_map.py first, without --retrieval-only)
"""
import json
from pathlib import Path

controls = {c["id"]: c for c in json.load(open("data/processed/controls.json", encoding="utf-8"))}
doc = json.load(open("data/sample_policy.json", encoding="utf-8"))
scope = doc["scope"]["controls"]
policy = {p["id"]: p for p in doc["statements"]}
res = json.load(open("reports/map_results.json"))["results"]

support = {c: [] for c in scope}
for sid, r in res.items():
    for j in r.get("judged", []):
        if j["verdict"] in ("yes", "partial") and j["control"] in support:
            support[j["control"]].append((sid, j["verdict"], bool(j["flag"])))

full, partial, none = [], [], []
for c in scope:
    s = support[c]
    if any(v == "yes" and not f for _, v, f in s):
        full.append(c)
    elif s:
        partial.append(c)
    else:
        none.append(c)

lines = ["# Policy gap report (DRAFT, for human review)", "",
         "Generated by an LLM-assisted mapping against NIST SP 800-53 Rev 5. "
         "A reviewer must confirm every line before it is used in an audit.", "",
         f"Scope: {len(scope)} controls (illustrative set). "
         f"Supported: {len(full)}, partially supported or needs review: {len(partial)}, "
         f"no policy support found: {len(none)}.", ""]
for title, group in (("No policy support found (gaps)", none),
                     ("Partial or needs review", partial),
                     ("Supported", full)):
    lines += [f"## {title}", ""]
    for c in group:
        src = ", ".join(sorted({sid for sid, _, _ in support[c]})) or "-"
        lines.append(f"- **{c}** {controls[c]['title']} (policy statements: {src})")
    lines.append("")

Path("reports").mkdir(exist_ok=True)
Path("reports/gap_report.md").write_text("\n".join(lines), encoding="utf-8")
print("\n".join(lines[:8]))
print(f"\nGaps: {none}")
print("Saved reports/gap_report.md")
